CREATE TABLE IF NOT EXISTS personagem (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    classe VARCHAR(100) NOT NULL,
    raca VARCHAR(100) NOT NULL,
    nivel VARCHAR(100) NOT NULL,
    forca INT NOT NULL,
    dex INT NOT NULL,
    con INT NOT NULL,
    inte INT NOT NULL,
    sab INT NOT NULL,
    car INT NOT NULL,
    data_criacao DATE
);